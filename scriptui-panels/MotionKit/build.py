"""Build the Motion Kit bundles from src/.

EffectCraft installs a ScriptUI panel by copying one file, so every panel is one self-contained
bundle: src/core/*.js, src/tools/<category>/*.js (widgets in src/tools/widgets/) and
src/extras/*.js (each sorted), then src/main.js, wrapped in one function. The bundles differ
only in their `var MK_PANEL = ...;` line. `Motion Kit.jsx` is the one to install; the single
panels in dist/extra/ are optional, for docking several at once.

    python3 build.py               write dist/
    python3 build.py --out DIR     write DIR/ instead (parallel builds use private folders)
    python3 build.py --check       exit 1 if the output folder is out of date or has bundles the
                                   build doesn't write
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"

# Output file (relative to the output folder) -> the value of MK_PANEL in it.
BUNDLES = [
    ("Motion Kit.jsx", '"all"'),
    ("extra/Motion Kit 1.jsx", "1"),
    ("extra/Motion Kit 2.jsx", "2"),
    ("extra/Motion Kit 3.jsx", "3"),
    ("extra/Motion Kit 4.jsx", "4"),
    ("extra/Motion Kit Menu.jsx", '"menu"'),
    ("motionkit-lib.jsx", "null"),
]

HEADER = (
    "// SPDX-License-Identifier: MIT OR Apache-2.0\n"
    "// Motion Kit for EffectCraft. Generated by build.py from src/, do not edit.\n"
)

# ES3-style rule (spec section 0): old-style script syntax only. Checked on code with strings and
# comments removed, so the words may appear in either.
FORBIDDEN = [
    (re.compile(r"=>"), "arrow function"),
    (re.compile(r"\blet\s+[A-Za-z_$\[{]"), "let"),
    (re.compile(r"\bconst\s+[A-Za-z_$\[{]"), "const"),
    (re.compile(r"`"), "template literal"),
    (re.compile(r"\bclass\s+[A-Za-z_$]"), "class"),
]


def sources():
    files = sorted((SRC / "core").glob("*.js"))
    files += sorted((SRC / "tools").glob("*/*.js"), key=lambda p: p.relative_to(SRC).as_posix())
    files += sorted((SRC / "extras").glob("*.js"))
    files.append(SRC / "main.js")
    return files


def strip_strings_and_comments(code):
    """Blank out string literals and comments (regex literals are left as they are)."""
    out, i, n = [], 0, len(code)
    while i < n:
        c = code[i]
        if c in "\"'":
            j = i + 1
            while j < n and code[j] != c and code[j] != "\n":
                j += 2 if code[j] == "\\" else 1
            out.append('""')
            i = j + 1
        elif code.startswith("//", i):
            j = code.find("\n", i)
            i = n if j < 0 else j
        elif code.startswith("/*", i):
            j = code.find("*/", i + 2)
            out.append("\n" * code.count("\n", i, n if j < 0 else j))
            i = n if j < 0 else j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def lint(path, text):
    errors = []
    for lineno, line in enumerate(strip_strings_and_comments(text).split("\n"), 1):
        for pattern, what in FORBIDDEN:
            if pattern.search(line):
                errors.append(f"{path}:{lineno}: {what} is not ES3-style JavaScript")
    return errors


def body():
    """The shared bundle text after the MK_PANEL line, plus lint errors."""
    errors, parts = [], []
    for f in sources():
        rel = f.relative_to(ROOT).as_posix()
        text = f.read_text(encoding="utf-8")
        errors += lint(rel, text)
        # The bundle carries one SPDX line at the top; drop the sources' own.
        text = re.sub(r"\A// SPDX-License-Identifier:[^\n]*\n", "", text)
        parts.append(f"// ---- {rel}\n{text.rstrip()}\n")
    main = parts.pop()
    out = (
        "(function (thisObj) {\n"
        "// One Motion Kit per scripting context: a panel opened after another reuses its model.\n"
        "var MK = $.global.MotionKit && $.global.MotionKit.__mk;\n"
        "if (!MK) MK = (function () {\n"
        "var MK = {};\n"
        + "\n".join(parts)
        + "return MK;\n"
        "})();\n"
        + main
        + "})(this);\n"
    )
    return out, errors


def render():
    text, errors = body()
    return {name: HEADER + f"var MK_PANEL = {value};\n" + text for name, value in BUNDLES}, errors


def main():
    ap = argparse.ArgumentParser(description="Build the Motion Kit bundles.")
    ap.add_argument("--out", default=str(ROOT / "dist"), help="output folder (default: dist/ next to build.py)")
    ap.add_argument("--check", action="store_true", help="exit 1 if the output folder is out of date")
    args = ap.parse_args()
    out = Path(args.out).resolve()
    files, errors = render()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if args.check:
        stale = [n for n, t in files.items() if not (out / n).is_file() or (out / n).read_text(encoding="utf-8") != t]
        # Bundles the build no longer writes (a single panel left outside extra/, say).
        stray = sorted(p.relative_to(out).as_posix() for p in out.rglob("*.jsx") if p.relative_to(out).as_posix() not in files)
        if stale or stray:
            what = ([", ".join(stale) + " out of date"] if stale else []) + ([", ".join(stray) + " not built any more"] if stray else [])
            print(f"{out}: " + "; ".join(what) + " (run python3 build.py, delete files it doesn't build)", file=sys.stderr)
            return 1
        print(f"{out} is up to date ({len(files)} files)")
        return 0
    for name, text in files.items():
        (out / name).parent.mkdir(parents=True, exist_ok=True)
        (out / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} files to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
